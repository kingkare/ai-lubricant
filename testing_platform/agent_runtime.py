"""Agent runtime — dsh (DeepSeek Harness) driver for the testing platform.

Wraps the official ``deepseek-harness-sdk`` (import name ``deepseek_harness``). The
SDK spawns a ``dsh`` subprocess that connects to the platform gateway
(``base_url``/``api_key``) for inference and to the testing MCP server for
tool calls — so the AI测试者 can drive any of the 107 testing methods
(``mcp__testing__scenario.create`` etc.).

Design (``plans/10-dsh-integration.md`` §五):

* ``base_url``/``api_key`` point at the platform gateway (``127.0.0.1:8001``).
* MCP injection goes through a ``cordis.patch.yml`` overlay that registers the
  ``@deepseek-ai/dsh-mcp-client`` plugin pointing at our Streamable HTTP MCP
  server — passed via ``DeepSeekHarnessConfig(patches=(...))``.
* ``on_notification`` → SSE events for the chat backend.

The SDK is **synchronous** (``harness.run`` blocks); ``run_async`` bridges it
to a worker thread so the FastAPI handler stays async and can stream events.
"""
from __future__ import annotations

import asyncio
import os
import threading
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, AsyncIterator, Awaitable, Callable, Optional

# ── defaults ────────────────────────────────────────────────────────────────
#: Default gateway base_url (the platform runs on 8001).
DEFAULT_BASE_URL = os.environ.get("TESTING_DSH_BASE_URL", "http://127.0.0.1:8001/v1")

#: Default model — small/fast; callers may override per chat.
DEFAULT_MODEL = os.environ.get("TESTING_DSH_MODEL", "claude-haiku-4-5-20251001")

#: Default dsh HOME — isolated from the project .venv; profiles live here.
DEFAULT_DSH_HOME = os.environ.get("TESTING_DSH_HOME", str(Path.cwd() / ".dsh-home"))

#: Default profile (must exist under ``$DSH_HOME/profiles/``).
DEFAULT_PROFILE = os.environ.get("TESTING_DSH_PROFILE", "sdk-minimal")

#: Default workspace for the dsh subprocess (cwd).
DEFAULT_CWD = os.environ.get("TESTING_DSH_CWD", str(Path.cwd()))

#: Our MCP server URL (Streamable HTTP). The chat handler overrides if behind a proxy.
DEFAULT_MCP_URL = os.environ.get("TESTING_DSH_MCP_URL", "http://127.0.0.1:8001/api/v1/testing/mcp")


class DshRuntimeError(RuntimeError):
    """dsh 配置/运行失败（缺包、缺凭据、子进程失败…）。"""


# ── cordis patch: inject the testing MCP server ──────────────────────────────

_CORDIS_PATCH_TEMPLATE = """\
# Auto-generated by testing_platform.agent_runtime — registers the testing
# platform MCP server (Streamable HTTP) so dsh can call any of the 107 testing
# methods via mcp__testing__<tool_name>.
- insert:
    - id: testing-mcp
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: testing
        transport: streamable-http
        url: {mcp_url}
        headers:
          {auth_header}
"""


def write_cordis_patch(*, mcp_url: str, mcp_token: Optional[str] = None, dest_dir: Optional[Path] = None) -> Path:
    """Write a cordis patch yml registering the testing MCP server.

    Returns the path (caller passes it to ``DeepSeekHarnessConfig.patches``).
    ``mcp_token`` is optional server-side auth; omitted when the MCP server is
    open within the platform's loopback (design: testing MCP is gateway-side).
    """
    dest = Path(dest_dir or DEFAULT_DSH_HOME) / "testing-mcp.cordis.patch.yml"
    dest.parent.mkdir(parents=True, exist_ok=True)
    header_line = 'Authorization: "Bearer {}"'.format(mcp_token) if mcp_token else "{}"
    dest.write_text(_CORDIS_PATCH_TEMPLATE.format(mcp_url=mcp_url, auth_header=header_line), encoding="utf-8")
    return dest


# ── config ──────────────────────────────────────────────────────────────────

@dataclass
class DshConfig:
    """Resolved dsh runtime config (one per chat run)."""

    api_key: str
    base_url: str = DEFAULT_BASE_URL
    model: str = DEFAULT_MODEL
    cwd: str = DEFAULT_CWD
    dsh_home: str = DEFAULT_DSH_HOME
    profile: str = DEFAULT_PROFILE
    mcp_url: str = DEFAULT_MCP_URL
    mcp_token: Optional[str] = None
    max_tokens: int = 49152
    request_timeout_seconds: float = 300.0
    patches: tuple[str, ...] = field(default_factory=tuple)

    def to_sdk_config(self):
        """Build a ``DeepSeekHarnessConfig`` from this config."""
        try:
            from deepseek_harness import DeepSeekHarnessConfig
        except ImportError as exc:
            raise DshRuntimeError(
                "deepseek-harness-sdk 未安装（import 名 deepseek_harness）。"
                "装进主 .venv：pip install \"deepseek-harness-sdk @ git+https://github.com/deepseek-ai/deepseek-harness.git\""
            ) from exc
        return DeepSeekHarnessConfig(
            provider="deepseek-official",
            model=self.model,
            base_url=self.base_url,
            api_key=self.api_key,
            max_tokens=self.max_tokens,
            cwd=self.cwd,
            dsh_home=self.dsh_home,
            profile=self.profile,
            patches=self.patches,
            request_timeout_seconds=self.request_timeout_seconds,
        )


def build_config(
    *,
    api_key: str,
    model: Optional[str] = None,
    session_id: Optional[str] = None,
    mcp_token: Optional[str] = None,
    mcp_url: Optional[str] = None,
    cwd: Optional[str] = None,
) -> DshConfig:
    """Build a ``DshConfig`` with the testing MCP cordis patch attached.

    The patch points dsh's mcp-client at ``DEFAULT_MCP_URL`` so the AI测试者
    can call ``mcp__testing__<method>`` for any of the 107 testing methods.
    """
    cfg = DshConfig(
        api_key=api_key,
        model=model or DEFAULT_MODEL,
        mcp_url=mcp_url or DEFAULT_MCP_URL,
        mcp_token=mcp_token,
        cwd=cwd or DEFAULT_CWD,
    )
    patch_path = write_cordis_patch(mcp_url=cfg.mcp_url, mcp_token=mcp_token)
    cfg.patches = (str(patch_path),)
    return cfg


# ── 用例生成专用网关参数（一键生成工作流）────────────────────────────────────
#: 生成用例用的网关 base_url / model / key —— 可用 ``TESTING_GEN_*`` 覆盖。
#: 未配时回落平台网关（``DEFAULT_BASE_URL``）+ 调用方传入的 api_key（按项目解析）。
#: **读取惰性化**（与 GRAPHIFY_VENV 同坑）：模块导入期固化会吃掉「先 import 后
#: load_project_env()」的场景——测试里 monkeypatch.setenv 也改不动快照值。
GEN_BASE_URL = os.environ.get("TESTING_GEN_BASE_URL", DEFAULT_BASE_URL)
GEN_MODEL = os.environ.get("TESTING_GEN_MODEL", os.environ.get("TESTING_DSH_MODEL", "claude-sonnet-4-6"))
GEN_API_KEY = os.environ.get("TESTING_GEN_API_KEY", "")


def _gen_api_key() -> str:
    """当前生效的生成密钥（环境优先，退回导入期快照）。"""
    return os.environ.get("TESTING_GEN_API_KEY") or GEN_API_KEY


def _gen_base_url() -> str:
    return (os.environ.get("TESTING_GEN_BASE_URL") or GEN_BASE_URL).strip()


def _gen_model() -> str:
    return (os.environ.get("TESTING_GEN_MODEL") or os.environ.get("TESTING_DSH_MODEL") or GEN_MODEL).strip()


class GenerationConfigError(DshRuntimeError):
    """生成用例的网关参数缺失（无 key / 无 base_url）——显式报错，不静默。"""


def build_generation_config(
    *,
    api_key: Optional[str] = None,
    model: Optional[str] = None,
    base_url: Optional[str] = None,
    mcp_token: Optional[str] = None,
    mcp_url: Optional[str] = None,
    cwd: Optional[str] = None,
) -> DshConfig:
    """构建「一键生成用例 / AI 读仓库生成接口」的 dsh 配置。

    优先级：显式入参 > ``TESTING_GEN_*`` 环境变量 > 平台默认。
    ``api_key`` 通常由调用方按项目 created_by 解析（复用 chat 的 api_key 语义）；
    解析不到且环境也没配 → 抛 :class:`GenerationConfigError`（生成需密钥，不静默）。
    ``cwd``：Agent 的工作目录（读仓库生成接口时设为**仓库快照目录**，让 Agent 能直接读代码）。
    """
    key = (api_key or _gen_api_key() or "").strip()
    if not key:
        raise GenerationConfigError(
            "生成需要模型密钥：请配置 TESTING_GEN_API_KEY，或确保项目创建者有可用 API Key"
        )
    cfg = DshConfig(
        api_key=key,
        base_url=(base_url or _gen_base_url()).strip(),
        model=(model or _gen_model()).strip(),
        mcp_url=mcp_url or DEFAULT_MCP_URL,
        mcp_token=mcp_token,
        cwd=cwd or DEFAULT_CWD,
    )
    patch_path = write_cordis_patch(mcp_url=cfg.mcp_url, mcp_token=mcp_token)
    cfg.patches = (str(patch_path),)
    return cfg


# ── notification → SSE event ─────────────────────────────────────────────────

def notification_to_event(notification: Any) -> dict[str, Any]:
    """Normalize a dsh ``Notification`` into an SSE-ready event dict.

    Notifications carry ``method`` + ``payload``; the payload's ``event`` field
    (for ``session.event``) holds the typed event the AI测试者 cares about
    (``assistant/message``, ``tool/...``, ``turn/end`` …).
    """
    method = getattr(notification, "method", "") or ""
    payload = getattr(notification, "payload", {}) or {}
    event: dict[str, Any] = {"method": method}

    # session.event → unwrap the inner typed event
    if method == "session.event":
        inner = payload.get("event") if isinstance(payload, dict) else None
        if isinstance(inner, dict):
            event["type"] = inner.get("type", "")
            event["data"] = inner.get("data", {})
            return event
    # session.status → turn lifecycle marker
    if method == "session.status":
        event["type"] = "session/status"
        event["data"] = {"status": payload.get("status"), "sessionId": payload.get("sessionId")}
        return event
    # fallback: pass method + payload through
    event["type"] = method
    event["data"] = payload
    return event


# ── async bridge ────────────────────────────────────────────────────────────

async def run_chat(
    *,
    prompt: str,
    config: DshConfig,
    session_id: Optional[str] = None,
    on_event: Optional[Callable[[dict[str, Any]], Awaitable[None]]] = None,
) -> dict[str, Any]:
    """Run one dsh turn, streaming notifications as events.

    The SDK's ``harness.run`` is **synchronous and blocking** — it is executed
    in a worker thread; each notification is pushed back to the event loop via
    ``loop.call_soon_threadsafe`` and awaited on ``on_event``.

    Returns ``{"session_id", "final_response", "finish_reason", "events"}``.
    """
    loop = asyncio.get_running_loop()
    queue: asyncio.Queue[Optional[dict[str, Any]]] = asyncio.Queue()
    collected_events: list[dict[str, Any]] = []

    def on_notification(notification) -> None:
        # Called from the dsh worker thread — bridge to the loop safely.
        ev = notification_to_event(notification)
        loop.call_soon_threadsafe(queue.put_nowait, ev)

    def worker() -> None:
        try:
            from deepseek_harness import DeepSeekHarness
            harness = DeepSeekHarness(config.to_sdk_config())
            with harness:
                result = harness.run(prompt, session_id=session_id, on_notification=on_notification)
                final = {
                    "session_id": result.session_id,
                    "final_response": result.final_response or "",
                    "finish_reason": result.finish_reason,
                }
                loop.call_soon_threadsafe(queue.put_nowait, {"__final__": True, **final})
        except BaseException as exc:  # noqa: BLE001 — surface to the loop
            loop.call_soon_threadsafe(
                queue.put_nowait, {"__error__": True, "error": f"{type(exc).__name__}: {exc}"}
            )

    thread = threading.Thread(target=worker, daemon=True)
    thread.start()

    final: Optional[dict[str, Any]] = None
    error: Optional[str] = None
    while True:
        item = await queue.get()
        if item is None:
            continue
        if item.get("__final__"):
            final = {k: v for k, v in item.items() if not k.startswith("__")}
            break
        if item.get("__error__"):
            error = item["error"]
            break
        collected_events.append(item)
        if on_event is not None:
            await on_event(item)

    # Drain any straggling notifications (best-effort).
    thread.join(timeout=2.0)

    if error is not None:
        raise DshRuntimeError(error)
    if final is None:
        raise DshRuntimeError("dsh 运行未返回结果（超时或子进程意外退出）")

    final["events"] = collected_events
    return final


async def stream_chat(
    *,
    prompt: str,
    config: DshConfig,
    session_id: Optional[str] = None,
) -> AsyncIterator[dict[str, Any]]:
    """Async generator yielding each notification event, then a ``done`` event.

    Used by the SSE chat endpoint. The final ``done`` event carries
    ``final_response`` / ``finish_reason`` / ``session_id``.
    """
    loop = asyncio.get_running_loop()
    queue: asyncio.Queue[Optional[dict[str, Any]]] = asyncio.Queue()

    def on_notification(notification) -> None:
        ev = notification_to_event(notification)
        loop.call_soon_threadsafe(queue.put_nowait, ev)

    def worker() -> None:
        try:
            from deepseek_harness import DeepSeekHarness
            harness = DeepSeekHarness(config.to_sdk_config())
            with harness:
                result = harness.run(prompt, session_id=session_id, on_notification=on_notification)
                loop.call_soon_threadsafe(queue.put_nowait, {
                    "__final__": True,
                    "session_id": result.session_id,
                    "final_response": result.final_response or "",
                    "finish_reason": result.finish_reason,
                })
        except BaseException as exc:  # noqa: BLE001
            loop.call_soon_threadsafe(queue.put_nowait, {"__error__": True, "error": f"{type(exc).__name__}: {exc}"})

    thread = threading.Thread(target=worker, daemon=True)
    thread.start()

    while True:
        item = await queue.get()
        if item is None:
            continue
        if item.get("__final__"):
            yield {"type": "done", "data": {k: v for k, v in item.items() if not k.startswith("__")}}
            break
        if item.get("__error__"):
            yield {"type": "error", "data": {"error": item["error"]}}
            break
        yield item

    thread.join(timeout=2.0)


